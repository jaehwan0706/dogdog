-- ---------------------------------------------------------------------
-- 도시공원 (Park): 맞춤 산책 코스의 목적지 후보
--   출처: 전국도시공원정보표준데이터 (공공데이터포털 15012890, 지방자치단체 제공)
--   서버가 처음 뜰 때 테이블이 비어 있으면 resources/data/city_parks.csv.gz 를 읽어 채운다 (ParkDataLoader)
--   (공원명, 위도, 경도) 가 같은 행과 묘지공원은 넣지 않는다
--   park_type     : 원본 '공원구분' (근린공원, 어린이공원, 소공원, 수변공원 ...)
--   area_m2       : 공원면적 (㎡), 원본에 없으면 NULL
--   convenience   : 편익시설 (화장실, 음수대 등)
--   amenities     : 운동·유희·교양·기타시설을 이어 붙인 것
--   source_updated_at : 원본의 '데이터기준일자'
-- ---------------------------------------------------------------------
CREATE TABLE parks (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    name              VARCHAR(100)  NOT NULL,
    park_type         VARCHAR(30)   NOT NULL,
    latitude          DOUBLE PRECISION        NOT NULL,
    longitude         DOUBLE PRECISION        NOT NULL,
    area_m2           DOUBLE PRECISION        NULL,
    road_address      VARCHAR(200)  NULL,
    lot_address       VARCHAR(200)  NULL,
    convenience       VARCHAR(300)  NULL,
    amenities         VARCHAR(500)  NULL,
    source_updated_at DATE          NULL,
    CONSTRAINT pk_parks PRIMARY KEY (id)
);

-- 내 위치 주변(위도·경도 사각형) 조회용
CREATE INDEX idx_parks_lat_lng ON parks (latitude, longitude);
