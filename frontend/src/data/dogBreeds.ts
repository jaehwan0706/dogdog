const normalize = (value: string) => value.toLocaleLowerCase('ko-KR').replace(/\s+/g, '');

export function searchDogBreeds(query: string, limit = 8) {
  const needle = normalize(query);
  if (!needle) return [];

  return dogBreeds
    .map((breed, index) => {
      const normalized = normalize(breed);
      const matchIndex = normalized.indexOf(needle);
      return { breed, index, matchIndex };
    })
    .filter(({ matchIndex }) => matchIndex >= 0)
    .sort((a, b) => a.matchIndex - b.matchIndex || a.index - b.index)
    .slice(0, limit)
    .map(({ breed }) => breed);
}
